// Generates lib/data/sqlite/sqlite_schema.dart from a freshly migrated
// PostgreSQL database (pos-cloud-single-till-sqlite, stage 4).
//
// The SQLite schema is the PostgreSQL one at the latest migration, translated
// table by table: columns, keys, defaults, checks, foreign keys and indexes.
// Triggers are NOT generated — PL/pgSQL does not translate mechanically; the
// ones a cloud till needs are written by hand in sqlite_triggers.dart, and
// this tool prints every PostgreSQL trigger so none is missed.
//
//   dart run tool/gen_sqlite_schema.dart <scratch database name>
//
// Connects to 127.0.0.1:5432 as $USER (override with POS_PG_*). Creates the
// scratch database if missing, migrates it, reads it, and leaves it there.
// Never point it at a database that matters.
import 'dart:io';

import 'package:postgres/postgres.dart' as pg;
import 'package:shared_module/core/config/deployment.dart';
import 'package:shared_module/data/postgres/migrations.dart';
import 'package:shared_module/data/postgres/pos_database.dart';

Future<void> main(List<String> args) async {
  if (args.length != 1 || !args.single.startsWith('xorder_pos_schemagen')) {
    stderr.writeln('usage: gen_sqlite_schema.dart xorder_pos_schemagen[_…]');
    exit(64);
  }
  final name = args.single;
  final env = Platform.environment;
  final host = env['POS_PG_HOST'] ?? '127.0.0.1';
  final port = int.parse(env['POS_PG_PORT'] ?? '5432');
  final user = env['POS_PG_USER'] ?? env['USER']!;
  final password = env['POS_PG_PASSWORD'] ?? 'unused';

  final admin = await pg.Connection.open(
    pg.Endpoint(
      host: host,
      port: port,
      database: 'postgres',
      username: user,
      password: password,
    ),
    settings: const pg.ConnectionSettings(sslMode: pg.SslMode.disable),
  );
  final exists = await admin.execute(
    pg.Sql.named('SELECT 1 FROM pg_database WHERE datname = @n'),
    parameters: {'n': name},
  );
  if (exists.isEmpty) await admin.execute('CREATE DATABASE "$name"');
  await admin.close();

  final config = DeploymentConfig(
    mode: DeploymentMode.offline,
    databaseHost: host,
    databasePort: port,
    databaseName: name,
    databaseUser: user,
  );
  final db = PosDatabase(credentials: InMemoryPosDbCredentials(password));
  await PosMigrator(db).migrate(config);

  Future<List<List<Object?>>> q(String sql) async =>
      [for (final r in await db.query(config, sql)) r.toList()];

  final tables = [
    for (final r in await q(
      "SELECT table_name::text FROM information_schema.tables "
      "WHERE table_schema = 'public' AND table_type = 'BASE TABLE' "
      "AND table_name <> 'schema_migrations' ORDER BY table_name",
    ))
      r[0] as String,
  ];

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_sqlite_schema.dart from PostgreSQL '
        'migration ${posMigrations.last.version}. Do not edit by hand:')
    ..writeln('// change the PostgreSQL migration, then regenerate.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('/// The PostgreSQL migration this schema matches.')
    ..writeln('const sqliteSchemaMatchesMigration = '
        '${posMigrations.last.version};')
    ..writeln()
    ..writeln('/// Every table, then every index, in an order SQLite accepts.')
    ..writeln('const sqliteSchema = <String>[');

  final indexes = <String>[];
  for (final table in tables) {
    final columns = await q('''
      SELECT a.attname::text, format_type(a.atttypid, a.atttypmod)::text,
             a.attnotnull, pg_get_expr(d.adbin, d.adrelid)::text,
             a.attidentity::text
        FROM pg_attribute a
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
       WHERE a.attrelid = 'public.$table'::regclass AND a.attnum > 0
         AND NOT a.attisdropped
       ORDER BY a.attnum''');
    final constraints = await q('''
      SELECT conname::text, contype::text, pg_get_constraintdef(oid)::text,
             (SELECT array_agg(att.attname::text ORDER BY k.ord)
                FROM unnest(conkey) WITH ORDINALITY AS k(num, ord)
                JOIN pg_attribute att ON att.attrelid = conrelid
                 AND att.attnum = k.num)
        FROM pg_constraint
       WHERE conrelid = 'public.$table'::regclass
       ORDER BY contype, conname''');
    final pk = constraints.where((c) => c[1] == 'p').firstOrNull;
    final pkColumns = pk == null ? const <String>[] : _list(pk[3]);
    final singleIntPk = pkColumns.length == 1 &&
        columns.any((c) =>
            c[0] == pkColumns.single &&
            const {'bigint', 'integer', 'smallint'}.contains(c[1]));

    final lines = <String>[];
    for (final c in columns) {
      final column = c[0] as String;
      final type = c[1] as String;
      final notNull = c[2] as bool;
      final rawDefault = c[3] as String?;
      final identity = (c[4] as String?)?.isNotEmpty ?? false;
      final serial =
          identity || (rawDefault?.startsWith('nextval(') ?? false);
      if (singleIntPk && column == pkColumns.single) {
        lines.add('"$column" INTEGER PRIMARY KEY'
            '${serial ? ' AUTOINCREMENT' : ''}');
        continue;
      }
      final def = serial || rawDefault == null
          ? null
          : _default(rawDefault);
      lines.add([
        '"$column" ${_type(type)}',
        if (notNull) 'NOT NULL',
        if (def != null) 'DEFAULT $def',
      ].join(' '));
    }
    if (pk != null && !singleIntPk) {
      lines.add('PRIMARY KEY (${pkColumns.map((c) => '"$c"').join(', ')})');
    }
    for (final c in constraints) {
      final kind = c[1] as String;
      final def = c[2] as String;
      if (kind == 'u') lines.add(_sql(def));
      // RESTRICT is enforced by SQLite the moment the parent goes, even when
      // the same cascade is about to remove the child; PostgreSQL's order lets
      // the cascade clear it first. NO ACTION keeps the protection — a parent
      // with children left is still refused — checked at the statement's end.
      if (kind == 'f') {
        lines.add(_sql(def).replaceAll('ON DELETE RESTRICT', 'ON DELETE NO ACTION'));
      }
      if (kind == 'c') {
        final check = _check(def);
        if (check != null) lines.add('CONSTRAINT "${c[0]}" $check');
      }
    }
    out
      ..writeln("  '''")
      ..writeln('CREATE TABLE "$table" (')
      ..writeln(lines.map((l) => '  $l').join(',\n'))
      ..writeln(")''',");

    for (final r in await q(
      "SELECT indexdef::text FROM pg_indexes WHERE schemaname = 'public' "
      "AND tablename = '$table' AND indexname NOT IN "
      "(SELECT conname FROM pg_constraint WHERE contype IN ('p','u')) "
      'ORDER BY indexname',
    )) {
      indexes.add(_sql((r[0] as String)
          .replaceAll('public.', '')
          .replaceAll(RegExp(r' USING \w+'), '')));
    }
  }
  for (final index in indexes) {
    out.writeln("  '''$index''',");
  }
  out.writeln('];');

  final file = File('lib/data/sqlite/sqlite_schema.dart');
  await file.writeAsString(out.toString());
  stdout.writeln('${tables.length} tables, ${indexes.length} indexes → '
      '${file.path}');

  // Every PostgreSQL trigger, so the hand-written SQLite ones can be checked
  // against the full list.
  for (final r in await q('''
      SELECT event_object_table::text, trigger_name::text,
             string_agg(event_manipulation::text, ' OR '), action_timing::text
        FROM information_schema.triggers
       WHERE trigger_schema = 'public'
       GROUP BY 1, 2, 4 ORDER BY 1, 2''')) {
    stdout.writeln('TRIGGER ${r[0]}.${r[1]}: ${r[3]} ${r[2]}');
  }
  await db.close();
}

List<String> _list(Object? value) =>
    [for (final v in (value as List? ?? const [])) v.toString()];

String _type(String pgType) {
  final t = pgType.toLowerCase();
  if (t.endsWith('[]')) return 'TEXT'; // a JSON array
  if (t.startsWith('timestamp') || t == 'date' || t.startsWith('time')) {
    return 'TEXT'; // ISO-8601, UTC for instants
  }
  if (t.startsWith('numeric') || t == 'real' || t == 'double precision') {
    return 'NUMERIC';
  }
  return switch (t) {
    'bigint' || 'integer' || 'smallint' || 'boolean' => 'INTEGER',
    'bytea' => 'BLOB',
    _ => 'TEXT', // text, varchar, char, uuid, jsonb, json, inet, …
  };
}

/// A PostgreSQL default as a SQLite one, or null when it has none.
String? _default(String pg) {
  final d = pg.trim();
  if (d == 'now()' || d == 'CURRENT_TIMESTAMP') {
    return "(strftime('%Y-%m-%dT%H:%M:%f000Z', 'now'))";
  }
  if (d == 'CURRENT_DATE') return "(date('now'))";
  if (d == 'gen_random_uuid()') {
    return "(lower(hex(randomblob(4)) || '-' || hex(randomblob(2)) || '-4' || "
        "substr(hex(randomblob(2)), 2) || '-' || "
        "substr('89ab', 1 + (abs(random()) % 4), 1) || "
        "substr(hex(randomblob(2)), 2) || '-' || hex(randomblob(6))))";
  }
  if (d == 'true') return '1';
  if (d == 'false') return '0';
  if (RegExp(r"^'\{\}'::\w+\[\]$").hasMatch(d)) return "'[]'";
  final literal = RegExp(r"^('(?:[^']|'')*')::[\w ]+(\[\])?$").firstMatch(d);
  if (literal != null) return literal[1];
  if (RegExp(r'^-?\d+(\.\d+)?$').hasMatch(d)) return d;
  if (RegExp(r'^\(-?\d+\)$').hasMatch(d)) return d;
  return '($d)'; // left for SQLite to judge; the schema test will say
}

/// A constraint or index definition's SQL in SQLite's spelling.
String _sql(String def) => def
    .replaceAllMapped(
      RegExp(r'TRIM\(BOTH FROM ([^()]+)\)'),
      (m) => 'trim(${m[1]})',
    )
    .replaceAll('btrim(', 'trim(')
    .replaceAll(RegExp(r'::[a-z_ ]+(\[\])?'), '')
    .replaceAllMapped(
      RegExp(r'= ANY \(ARRAY\[(.*?)\]\)'),
      (m) => 'IN (${m[1]})',
    )
    .replaceAll(' NOT VALID', '');

/// A CHECK in SQLite's spelling, or null for one SQLite cannot express
/// (regular expressions); those are listed in the output for review.
String? _check(String def) {
  // `~~` is PostgreSQL's spelling of LIKE, not a regular expression.
  def = def.replaceAll(' !~~ ', ' NOT LIKE ').replaceAll(' ~~ ', ' LIKE ');
  if (def.contains(' ~ ') || def.contains(' ~* ') || def.contains('!~') ||
      def.contains('<@') || def.contains('@>')) {
    stdout.writeln('CHECK dropped (regex or array containment): $def');
    return null;
  }
  return _sql(def);
}
